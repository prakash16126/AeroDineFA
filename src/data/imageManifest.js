const rightsNotice = 'Photo content visually matched. Original license and attribution details are not recorded in the project; verify rights before commercial use.';

export const imageManifest = menu.map((dish) => {
  const image = verifiedLocalImages[dish.id];
  return {
    dishId: dish.id,
    imageUrl: image?.imageUrl ?? null,
    alt: image?.alt ?? `${dish.name} photograph awaiting manual verification`,
    source: image?.source ?? 'No suitable matching photograph found in the existing local assets.',
    sourcePage: image?.sourcePage ?? null,
    credit: image?.credit ?? null,
    license: image?.license ?? (image ? rightsNotice : 'Not assigned because no matching image has been verified.'),
    licenseUrl: image?.licenseUrl ?? null,
    verified: Boolean(image),
    status: image ? (image.license ? 'content-and-license-verified' : 'content-verified-rights-review') : 'needs-review',
  };
});

export function validateImageManifest(dishes, manifest, brokenDishIds = []) {
  const dishIds = new Set(dishes.map((dish) => dish.id));
  const manifestIds = new Set(manifest.map((image) => image.dishId));
  const mappingCounts = new Map();
  for (const image of manifest) mappingCounts.set(image.dishId, (mappingCounts.get(image.dishId) || 0) + 1);
  const urls = new Map();
  const imagesById = new Map();
  for (const image of manifest) {
    imagesById.set(image.dishId, image);
    if (image.imageUrl) urls.set(image.imageUrl, (urls.get(image.imageUrl) || 0) + 1);
  }
  const duplicateUrls = [...urls].filter(([, count]) => count > 1).map(([url]) => url);
  const brokenIds = new Set(brokenDishIds);
  for (const image of manifest) {
    if (!image.imageUrl) continue;
    try {
      const parsed = new URL(image.imageUrl, 'https://aerodine.invalid');
      if (!['http:', 'https:'].includes(parsed.protocol)) brokenIds.add(image.dishId);
    } catch {
      brokenIds.add(image.dishId);
    }
  }
  return {
    dishCount: dishes.length,
    mappedImageCount: manifest.filter((image) => image.imageUrl && image.verified).length,
    missingMappings: [...dishIds].filter((id) => !manifestIds.has(id)),
    orphanMappings: [...manifestIds].filter((id) => !dishIds.has(id)),
    duplicateMappings: [...mappingCounts].filter(([, count]) => count > 1).map(([id]) => id),
    missingImageUrls: manifest.filter((image) => !image.imageUrl).map((image) => image.dishId),
    duplicateUrls,
    brokenImages: manifest.filter((image) => brokenIds.has(image.dishId)).map((image) => image.dishId),
    unverifiedImages: manifest.filter((image) => !image.verified).map((image) => image.dishId),
    verifiedContent: manifest.filter((image) => image.verified).map((image) => image.dishId),
    imagesAwaitingReview: dishes
      .filter((dish) => {
        const image = imagesById.get(dish.id);
        return !image?.imageUrl || !image.verified;
      })
      .map(({ id, name }) => ({ id, name })),
  };
}

export const imageValidationReport = validateImageManifest(menu, imageManifest);

